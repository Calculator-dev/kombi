/** Messages computed in @kombi/shared (in Bosnian) for English visitors. */
export function translateQuoteError(message: string, locale: Locale): string {
  if (locale === "bs") return message;
  const min = message.match(/najmanje (\d+)/);
  if (min) return `In this period the minimum rental is ${min[1]} ${Number(min[1]) === 1 ? "day" : "days"}.`;
  const max = message.match(/Najduži najam preko stranice je (\d+)/);
  if (max) return `The longest rental through the site is ${max[1]} days. For longer, write to us.`;
  if (message.startsWith("Datum povratka")) return "The return date must be after the pickup date.";
  if (message.startsWith("Odabrano mjesto")) return "The chosen pickup place isn't available.";
  if (message.startsWith("Neispravan datum")) return "Invalid date.";
  return message;
}

/** "3 dana × 120 KM" from the shared price calculation, in English. */
export function translateRentalLine(label: string, locale: Locale): string {
  if (locale === "bs") return label;
  return label.replace(/^(\d+) (dan|dana) × /, (_, n: string) => `${n} ${n === "1" ? "day" : "days"} × `);
}

