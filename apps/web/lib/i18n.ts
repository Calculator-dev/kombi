/**
 * The public site in Bosnian (at /) and English (at /en). The admin panel,
 * the rental contract and the emails stay in Bosnian. What owners type
 * themselves (descriptions, extras, rental terms) is shown as they wrote it.
 */
export type Locale = "bs" | "en";

/** Pages that exist in English too, under /en. */
const TRANSLATED = ["/", "/kombiji", "/rezervacija", "/privatnost", "/kolacici"];
const hasEnglish = (path: string) => TRANSLATED.includes(path) || path.startsWith("/kombi/");

/** "/kombiji?x=1" → "/en/kombiji?x=1"; "/#paketi" → "/en#paketi". */
export function localePath(locale: Locale, href: string): string {
  if (locale === "bs" || !href.startsWith("/")) return href;
  if (href === "/" || href.startsWith("/#") || href.startsWith("/?")) return `/en${href.slice(1)}`;
  return `/en${href}`;
}

export const localeOf = (pathname: string): Locale => (pathname === "/en" || pathname.startsWith("/en/") ? "en" : "bs");

/** The same page in the other language (the homepage if it has no translation). */
export function switchPath(pathname: string): string {
  if (localeOf(pathname) === "en") return pathname.slice(3) || "/";
  return hasEnglish(pathname) ? localePath("en", pathname) : "/en";
}

export const plural = (n: number, one: string, few: string, many: string) =>
  n % 10 === 1 && n % 100 !== 11 ? one : n % 10 >= 2 && n % 10 <= 4 && (n % 100 < 10 || n % 100 >= 20) ? few : many;

