import { existsSync, mkdirSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { PGlite } from "@electric-sql/pglite";
import type { PgDatabase, PgQueryResultHKT } from "drizzle-orm/pg-core";
import { drizzle as drizzlePg } from "drizzle-orm/node-postgres";
import { migrate as migratePg } from "drizzle-orm/node-postgres/migrator";
import { drizzle as drizzlePglite } from "drizzle-orm/pglite";
import { migrate as migratePglite } from "drizzle-orm/pglite/migrator";
import pg from "pg";
import * as schema from "./schema";

export { schema };

/** Drizzle database, the same type whichever driver is underneath. */
export type Database = PgDatabase<PgQueryResultHKT, typeof schema>;
/** Either the database or an open transaction. */
export type Executor = Database | Parameters<Parameters<Database["transaction"]>[0]>[0];

export interface Db {
  kind: "postgres" | "pglite";
  orm: Database;
  close(): Promise<void>;
}

/** Folder with the SQL migrations generated by `npm run db:generate`. */
function migrationsFolder(): string {
  const here = path.dirname(fileURLToPath(import.meta.url));
  // src/db/index.ts in development, dist/index.js after building
  const candidates = [
    process.env.MIGRATIONS_DIR,
    path.resolve(here, "../../drizzle"),
    path.resolve(here, "../drizzle"),
  ].filter((p): p is string => Boolean(p));
  const found = candidates.find((p) => existsSync(path.join(p, "meta", "_journal.json")));
  if (!found) throw new Error(`Drizzle migrations not found (looked in: ${candidates.join(", ")})`);
  return found;
}

/**
 * Production uses PostgreSQL (DATABASE_URL). Without it, an embedded Postgres
 * (PGlite) is used — on disk for development, in memory for tests — so the
 * same schema and migrations run everywhere. Pending migrations run on start.
 */
export interface DbSsl {
  mode: "off" | "require" | "verify";
  ca?: string;
}

function sslOptions(ssl: DbSsl | undefined): pg.PoolConfig["ssl"] {
  if (!ssl || ssl.mode === "off") return false;
  // "require" encrypts but trusts any certificate; "verify" also checks it (against `ca`, or the system CAs).
  return ssl.mode === "require" ? { rejectUnauthorized: false } : { rejectUnauthorized: true, ca: ssl.ca };
}

export async function createDb(opts: { url?: string; dataDir?: string | null; ssl?: DbSsl }): Promise<Db> {
  const folder = migrationsFolder();
  if (opts.url) {
    const pool = new pg.Pool({ connectionString: opts.url, max: 10, ssl: sslOptions(opts.ssl) });
    const orm = drizzlePg(pool, { schema });
    await migratePg(orm, { migrationsFolder: folder });
    return { kind: "postgres", orm: orm as unknown as Database, close: () => pool.end() };
  }
  if (opts.dataDir) mkdirSync(opts.dataDir, { recursive: true });
  const client = opts.dataDir ? new PGlite(opts.dataDir) : new PGlite();
  await client.waitReady;
  const orm = drizzlePglite(client, { schema });
  await migratePglite(orm, { migrationsFolder: folder });
  return { kind: "pglite", orm: orm as unknown as Database, close: () => client.close() };
}
